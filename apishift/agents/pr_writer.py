"""PR Writer: Spark writes the title and summary; everything factual is rendered from artifacts."""
from __future__ import annotations

import html

from ..state import ChangeManifest, ImpactGraph, PRSummary, TestReport
from .common import as_json, structured_call

SYSTEM = """You are PR Writer, part of APIShift. Write a pull request title (under 72 characters) and a
short summary (3-5 sentences) for an automated API migration, plus notes a reviewer should check.
State only what the artifacts show. Do not claim anything is production-ready."""


def run(client, ledger, manifest: ChangeManifest, graph: ImpactGraph, diff_text: str, before: TestReport,
        after: TestReport, green: bool) -> PRSummary:
    user = (f"Outcome: {'all tests pass' if green else 'tests still failing; this will be a draft PR'}\n\n"
            f"ChangeManifest:\n{as_json(manifest)}\n\nImpactGraph:\n{as_json(graph)}\n\n"
            f"Tests before: {before.passed}/{before.collected} passing; after: {after.passed}/{after.collected}\n\n"
            f"Diff:\n{diff_text[-8000:]}")
    return structured_call(client, ledger, "pr_writer", SYSTEM, user, PRSummary)


def render_body(summary: PRSummary, manifest: ChangeManifest, graph: ImpactGraph, diff_text: str,
                before: TestReport, after: TestReport, guardrails: list[tuple[str, bool, str]],
                totals: dict, attempts: int, green: bool) -> str:
    esc = lambda s: html.escape(s, quote=False)  # model text is data, never markup
    lines = [f"## {esc(summary.title)}", "",
             ("**Status: all tests pass.**" if green else "**Status: needs human review. Tests still fail after the heal limit.**"),
             "", esc(summary.summary), "", "### Breaking changes handled", "",
             "| Id | Category | Old | New | Rule |", "| --- | --- | --- | --- | --- |"]
    for c in manifest.changes:
        lines.append(f"| {c.id} | {c.category} | `{esc(c.old_target)}` | `{esc(c.new_target or '-')}` | {esc(c.migration_rule)} |")
    lines += ["", "### Impact graph", ""]
    for n in graph.nodes:
        lines.append(f"- `{n.file_path}` {esc(n.symbol)} (lines {', '.join(map(str, n.lines))}): {esc(n.action)}")
    for e in graph.edges:
        lines.append(f"  - {e.from_node} {e.kind} {e.to_node}" + (f" (`{esc(e.field)}`)" if e.field else ""))
    lines += ["", "### Verification", "",
              f"- Before: {before.passed}/{before.collected} tests passing against the new API",
              f"- After: {after.passed}/{after.collected} tests passing ({attempts} patch attempt(s))", ""]
    lines += ["| Guardrail | Result | Detail |", "| --- | --- | --- |"]
    for name, ok, detail in guardrails:
        lines.append(f"| {name} | {'pass' if ok else 'FAIL'} | {esc(detail)} |")
    if summary.reviewer_notes:
        lines += ["", "### Reviewer notes", ""] + [f"- {esc(n)}" for n in summary.reviewer_notes]
    lines += ["", f"Model usage: {totals.get('calls', 0)} calls, {totals.get('input_tokens', 0):,} input tokens "
              f"({totals.get('cached_tokens', 0):,} cached), {totals.get('output_tokens', 0):,} output, "
              f"${totals.get('cost_usd', 0):.3f}", "", "<details><summary>Full diff</summary>", "", "```diff",
              diff_text, "```", "</details>", "", "_Generated by APIShift. Tests were read-only throughout._"]
    return "\n".join(lines)
